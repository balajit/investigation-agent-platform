#!/usr/bin/env python3
"""IAP operator home manager — systematic operator files outside the repo.

The repo holds zero operator data; the runtime reads only IAP datastores.
This CLI owns the operator side: layout, validation, seeding, backups.

Home layout (IAP_OPERATOR_HOME, default ~/workspace/.iap):
  README.md                          generated by init; runbook entry point
  scopes/<org>/<env>/app.env         env lever: shared 90% + env-varying 10%
                                     (persistence, external endpoints)
  scopes/<org>/<app>/<env>/
    app.env                          app lever: deltas only (usually near-empty)
    oracle.yaml                      DB credentials, 0600 (loader schema)
    seed/*.yaml                      operator-owned seed payloads
  seed/state.json                    what was seeded when
  backups/                           timestamped snapshots

Resolution (later wins, provenance-annotated): env lever → app leaf.
Scopes are self-contained per operator; the operator dir is the permission
boundary (0700, doctor-enforced). Secret keys are DENIED in lever files
(fail-closed): credentials live only in per-leaf oracle.yaml.

Usage:
  .venv/bin/python scripts/iap-operator.py --home PATH init
  .venv/bin/python scripts/iap-operator.py doctor [--scope ORG/APP/ENV]
  eval "$(.venv/bin/python scripts/iap-operator.py env --scope ORG/APP/ENV)"
  .venv/bin/python scripts/iap-operator.py seed [--scope ORG/APP/ENV] [--dry-run]
  .venv/bin/python scripts/iap-operator.py status [--scope ORG/APP/ENV]
  .venv/bin/python scripts/iap-operator.py backup [--include-credentials]
  .venv/bin/python scripts/iap-operator.py sync [--scope ORG/APP/ENV] [--dry-run]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import stat
import sys
import tarfile
from datetime import UTC, datetime
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SRC = REPO_ROOT / "src"
if SRC.is_dir() and str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

SEGMENT_RE = re.compile(r"^[A-Za-z0-9_.-]+$")
ENV_LINE_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)=(.*)$")
# Secret keys banned from lever/app.env overlays (fail-closed): credentials
# belong in per-leaf oracle.yaml (0600) only.
SECRET_KEY_RE = re.compile(
    r"(USER_NAME|PASSWORD|JDBC_URL|_KEY$|_TOKEN$|_SECRET$|SECRET_|PASSWD|PRIVATE_)", re.IGNORECASE
)

README_TEMPLATE = """# IAP operator home

Operator-owned files. NOTHING here is committed to the repo — the runtime
reads only IAP datastores, and this directory is populated inward through
`scripts/iap-operator.py` (validated paths only).

Layout: `scopes/<org>/<env>/app.env` env levers (shared + env-varying config),
`scopes/<org>/<app>/<env>/` app leaves (`app.env` deltas, `oracle.yaml`
credentials at 0600, `seed/*.yaml` payloads). `seed/state.json` is the seed
ledger; `backups/` holds snapshots. Manage exclusively via:

  .venv/bin/python scripts/iap-operator.py --home PATH init|doctor|env|seed|status|backup
"""


def resolve_home(args: argparse.Namespace) -> Path:
    if getattr(args, "home", None):
        return Path(args.home).expanduser()
    return Path(os.environ.get("IAP_OPERATOR_HOME", "~/workspace/.iap")).expanduser()


def split_scope(scope: str) -> tuple[str, str, str]:
    """Validate org/app/env scope path; raise SystemExit on misuse."""
    parts = str(scope or "").strip().split("/")
    if len(parts) != 3 or any(not SEGMENT_RE.match(p) for p in parts) or any(p in (".", "..") for p in parts):
        raise SystemExit(f"ERROR: bad --scope (want <org>/<app>/<env>): {scope}")
    return parts[0], parts[1], parts[2]


def resolve_scope(args: argparse.Namespace) -> str:
    return str(getattr(args, "scope", "") or "").strip()


def fail(msg: str, code: int = 1) -> int:
    print(f"ERROR: {msg}", file=sys.stderr)
    return code


def _leaf_dir(home: Path, scope: str) -> Path:
    org, app, env = split_scope(scope)
    return home / "scopes" / org / app / env


def _lever_file(home: Path, scope: str) -> Path:
    org, _app, env = split_scope(scope)
    return home / "scopes" / org / env / "app.env"


def _known_scopes(home: Path) -> list[str]:
    base = home / "scopes"
    out = []
    if not base.is_dir():
        return out
    for org in sorted(base.iterdir()):
        if not org.is_dir() or org.name.startswith("_"):
            continue
        for app in sorted(org.iterdir()):
            if not app.is_dir():
                continue
            for env in sorted(app.iterdir()):
                if env.is_dir():
                    out.append(f"{org.name}/{app.name}/{env.name}")
    return out


def cmd_init(args: argparse.Namespace) -> int:
    home = resolve_home(args)
    if (home / "README.md").exists() and not getattr(args, "force", False):
        return fail(f"operator home already initialized: {home} (use --force to rewrite README)")
    for sub in ("scopes", "seed", "backups"):
        (home / sub).mkdir(parents=True, exist_ok=True)
    (home / "README.md").write_text(README_TEMPLATE, encoding="utf-8")
    (home / "seed" / "state.json").write_text("{}\n", encoding="utf-8")
    print(f"initialized operator home: {home}")
    return 0


def _check_perms(path: Path) -> str | None:
    """None when group/other have no access; reason string otherwise."""
    mode = stat.S_IMODE(path.stat().st_mode)
    if mode & 0o077:
        return f"{path} is group/other-accessible (mode {oct(mode)})"
    return None


def _parse_dotenv(path: Path) -> tuple[dict[str, str], list[str]]:
    values: dict[str, str] = {}
    errors: list[str] = []
    for lineno, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = ENV_LINE_RE.match(line)
        if not match:
            errors.append(f"{path}:{lineno}: malformed line")
            continue
        name, val = match.group(1), match.group(2).strip()
        if len(val) >= 2 and val[0] == val[-1] and val[0] in "\"'":
            val = val[1:-1]
        values[name] = val
    return values, errors


def _deny_secrets(where: str, values: dict[str, str]) -> list[str]:
    bad = sorted(name for name in values if SECRET_KEY_RE.search(name))
    return [f"{where}: secret key in shared layer (move to oracle.yaml): {name}" for name in bad]


def _read_overlay(path: Path, label: str) -> tuple[dict[str, str], dict[str, str], list[str]]:
    """Returns (values, provenance, errors); provenance maps KEY -> label."""
    if not path.is_file():
        return {}, {}, []
    values, errors = _parse_dotenv(path)
    errors = [f"{label}: {e}" for e in errors]
    errors.extend(_deny_secrets(label, values))
    return values, {name: label for name in values}, errors


def cmd_doctor(args: argparse.Namespace) -> int:
    home = resolve_home(args)
    problems: list[str] = []
    for sub in ("scopes", "seed", "backups"):
        if not (home / sub).is_dir():
            problems.append(f"missing directory: {home / sub} (run init)")
    scope = resolve_scope(args)
    scopes = [scope] if scope else _known_scopes(home)
    if scope and scope not in _known_scopes(home):
        problems.append(f"unknown scope: {scope}")
    for item in scopes:
        try:
            org = item.split("/")[0]
        except Exception:
            problems.append(f"bad scope shape: {item}")
            continue
        opdir = home / "scopes" / org
        if opdir.is_dir():
            reason = _check_perms(opdir)
            if reason:
                problems.append(reason + " — operator dir must be 0700 (app names hidden)")
        sdir = home / "scopes" / Path(item)
        cred = sdir / "oracle.yaml"
        if cred.is_file():
            reason = _check_perms(cred)
            if reason:
                problems.append(reason + " — chmod 0600")
            text = cred.read_text(encoding="utf-8")
            for key in ("app:", "environment:", "databases:", "user_name:", "password:", "jdbcUrl:"):
                if key not in text:
                    problems.append(f"{item}/oracle.yaml: missing key {key}")
        for label, path in (("lever", _lever_file(home, item)), ("leaf", sdir / "app.env")):
            if path.is_file():
                reason = _check_perms(path)
                if reason:
                    problems.append(reason + " — chmod 0600")
                _, _, errors = _read_overlay(path, f"{item}:{label}")
                problems.extend(errors)
    if problems:
        print(f"doctor: {len(problems)} problem(s) in {home}:")
        for problem in problems:
            print(f"  - {problem}")
        return 1
    print(f"doctor: {home} OK ({len(scopes)} scope(s))")
    return 0


def _merged_overlay(home: Path, scope: str) -> tuple[dict[str, str], dict[str, str], list[str]]:
    """Merge env lever -> app leaf; returns (values, provenance, errors)."""
    lever_vals, lever_prov, lever_err = _read_overlay(_lever_file(home, scope), f"{scope}:lever")
    leaf_vals, leaf_prov, leaf_err = _read_overlay(
        home / "scopes" / Path(scope) / "app.env", f"{scope}:leaf"
    )
    values = {**lever_vals, **leaf_vals}
    provenance = {**lever_prov, **leaf_prov}
    return values, provenance, lever_err + leaf_err


def cmd_env(args: argparse.Namespace) -> int:
    home = resolve_home(args)
    scope = resolve_scope(args)
    if not scope:
        return fail("env requires --scope <org>/<app>/<env>")
    split_scope(scope)
    values, provenance, errors = _merged_overlay(home, scope)
    if errors:
        for error in errors:
            print(f"ERROR: {error}", file=sys.stderr)
        return 1
    if not values:
        return fail(f"no overlay values for scope: {scope}")
    for name, val in values.items():
        # Eval-safe export with provenance comment; values never touch logs.
        print(f"export {name}='{val.replace(chr(39), chr(39) + chr(92) + chr(39) + chr(39))}' # {provenance[name]}")
    return 0


def _file_hash(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _load_state(home: Path) -> dict:
    path = home / "seed" / "state.json"
    if not path.is_file():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {}
    return data if isinstance(data, dict) else {}


def _save_state(home: Path, state: dict) -> None:
    (home / "seed").mkdir(parents=True, exist_ok=True)
    (home / "seed" / "state.json").write_text(json.dumps(state, indent=2) + "\n", encoding="utf-8")


def _seed_files(home: Path, scopes: list[str]) -> list[tuple[str, Path]]:
    out = []
    for scope in scopes:
        sdir = home / "scopes" / Path(scope) / "seed"
        if sdir.is_dir():
            out.extend((scope, p) for p in sorted(sdir.glob("*.yaml")))
    return out


def cmd_seed(args: argparse.Namespace) -> int:
    import asyncio

    from investigation_agent_platform.infrastructure.configuration.config import (
        load_application_profile_from_file,
    )

    home = resolve_home(args)
    scope = resolve_scope(args)
    scopes = [scope] if scope else _known_scopes(home)
    if scope and scope not in _known_scopes(home):
        return fail(f"unknown scope: {scope}")
    files = _seed_files(home, scopes)
    if not files:
        return fail("no seed payloads: scopes/<org>/<app>/<env>/seed/*.yaml")
    state = _load_state(home)
    profiles = []
    for item, path in files:
        try:
            profile = load_application_profile_from_file(path)
        except Exception as exc:
            return fail(f"{item}/{path.name}: validation failed: {exc}")
        digest = _file_hash(path)
        key = f"{item}/{profile.tenant_id}/{profile.id}"
        entry = state.get(key, {})
        if entry.get("version") == profile.version and entry.get("sha256") == digest:
            print(f"SKIP {item}/{path.name}: {key} v{profile.version} already seeded ({digest[:12]})")
            continue
        profiles.append((item, path, profile, digest, key))
    if args.dry_run:
        for item, path, profile, digest, key in profiles:
            print(
                f"DRY-RUN {item}/{path.name}: tenant={profile.tenant_id} id={profile.id} "
                f"version={profile.version} sha={digest[:12]}"
            )
        print(f"dry-run: {len(profiles)} profile(s) would seed, nothing written")
        return 0
    db_uri = os.environ.get("IAP_DATABASE_URI", "")
    if not db_uri:
        return fail("IAP_DATABASE_URI is required (or pass --dry-run)")
    if db_uri.startswith("postgresql://"):
        db_uri = "postgresql+asyncpg://" + db_uri[len("postgresql://") :]

    async def _save() -> int:
        from sqlalchemy.ext.asyncio import async_sessionmaker, create_async_engine

        from investigation_agent_platform.infrastructure.persistence.profile_repository import (
            SqlAlchemyApplicationProfileRepository,
        )

        engine = create_async_engine(db_uri)
        try:
            repo = SqlAlchemyApplicationProfileRepository(async_sessionmaker(engine, expire_on_commit=False))
            for item, path, profile, digest, key in profiles:
                await repo.save(profile.tenant_id, profile)
                state[key] = {
                    "version": profile.version,
                    "sha256": digest,
                    "source": f"{item}/{path.name}",
                    "seeded_at": datetime.now(UTC).isoformat(),
                }
                print(f"SEEDED {item}/{path.name}: {key} v{profile.version}")
            return 0
        finally:
            await engine.dispose()

    code = asyncio.run(_save())
    if code == 0:
        _save_state(home, state)
    return code


def cmd_status(args: argparse.Namespace) -> int:
    home = resolve_home(args)
    scope = resolve_scope(args)
    if scope:
        split_scope(scope)
        if scope not in _known_scopes(home):
            return fail(f"unknown scope: {scope}")
    scopes = [scope] if scope else _known_scopes(home)
    print(f"operator home: {home}")
    state = _load_state(home)
    for item in scopes:
        sdir = home / "scopes" / Path(item)
        cred = "oracle.yaml" if (sdir / "oracle.yaml").is_file() else "-"
        overlay = "app.env" if (sdir / "app.env").is_file() else "-"
        lever = "lever" if _lever_file(home, item).is_file() else "-"
        seeds = sorted((sdir / "seed").glob("*.yaml")) if (sdir / "seed").is_dir() else []
        print(f"scope {item}: lever={lever} cred={cred} overlay={overlay} payloads={[p.name for p in seeds]}")
    print(f"recorded seeds: {len(state)}")
    for key, entry in sorted(state.items()):
        print(f"  - {key} v{entry.get('version')} sha={str(entry.get('sha256', ''))[:12]}")
    backups = sorted((home / "backups").glob("*.tar.gz")) if (home / "backups").is_dir() else []
    print(f"backups: {len(backups)}" + (f" (latest {backups[-1].name})" if backups else ""))
    return 0


def cmd_backup(args: argparse.Namespace) -> int:
    home = resolve_home(args)
    stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
    (home / "backups").mkdir(parents=True, exist_ok=True)
    dest = home / "backups" / f"operator-{stamp}.tar.gz"
    include_creds = bool(getattr(args, "include_credentials", False))
    if include_creds:
        print("WARNING: backup includes DB credentials (oracle.yaml files) — guard this archive.", file=sys.stderr)
    with tarfile.open(dest, "w:gz") as tar:
        if (home / "scopes").is_dir():
            for path in sorted((home / "scopes").rglob("*")):
                if not path.is_file():
                    continue
                rel = path.relative_to(home)
                if not include_creds and path.name == "oracle.yaml":
                    continue
                tar.add(path, arcname=str(rel))
        if (home / "seed").is_dir():
            tar.add(home / "seed", arcname="seed")
    print(f"backup: {dest}")
    return 0


def cmd_sync(args: argparse.Namespace) -> int:
    """Fingerprint-gated re-analysis: rebuild graph artifacts only on SHA change.

    Subsumes ad-hoc graph rebuilds (acquired-judgement §7 thread). Dry-run
    reports which scopes would rebuild; live run records the new fingerprint
    in seed/state.json so repeats prove no-rebuild.
    """
    from pathlib import Path as _Path  # local import keeps CLI startup cheap

    home = resolve_home(args)
    scope = getattr(args, "scope", "") or ""
    dry = bool(getattr(args, "dry_run", False))
    scopes = [scope] if scope else _known_scopes(home)
    if scope and scope not in _known_scopes(home):
        return fail(f"unknown scope: {scope}")
    state = _load_state(home)
    rebuilt: list[str] = []
    skipped: list[str] = []
    for item in scopes:
        key = f"{item}/graph-fingerprint"
        entry = state.get(key, {})
        marker = _Path(home) / "scopes" / _Path(item) / "seed" / ".graph_sha"
        if not marker.is_file():
            skipped.append(item)
            print(f"sync: {item} skipped (no .graph_sha marker — fail-closed, no version bump)", file=sys.stderr)
            continue
        current = marker.read_text(encoding="utf-8").strip()
        if not current:
            skipped.append(item)
            print(f"sync: {item} skipped (empty .graph_sha marker)", file=sys.stderr)
            continue
        if entry.get("sha256") == current:
            skipped.append(item)
            continue
        rebuilt.append(item)
        if not dry:
            state[key] = {"sha256": current, "version": int(entry.get("version", 0)) + 1}
    if not dry:
        _save_state(home, state)
    print(f"sync: rebuilt={sorted(rebuilt)} skipped={sorted(skipped)} dry_run={dry}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="IAP operator home manager.")
    parser.add_argument("--home", default="", help="Operator home (default $IAP_OPERATOR_HOME or ~/workspace/.iap).")
    parser.add_argument("--scope", default="", help="Scope <org>/<app>/<env> (some commands require it).")
    sub = parser.add_subparsers(dest="command", required=True)
    init = sub.add_parser("init", help="Scaffold the operator home.")
    init.add_argument("--force", action="store_true", help="Rewrite README even if initialized.")
    init.set_defaults(func=cmd_init)
    doctor = sub.add_parser("doctor", help="Fail-closed checks over the home (one scope or all).")
    doctor.set_defaults(func=cmd_doctor)
    env = sub.add_parser("env", help="Emit merged eval-able exports for a scope.")
    env.set_defaults(func=cmd_env)
    seed = sub.add_parser("seed", help="Validate + load seed payloads into the DB.")
    seed.add_argument("--dry-run", action="store_true")
    seed.set_defaults(func=cmd_seed)
    status = sub.add_parser("status", help="Inventory of the home.")
    status.set_defaults(func=cmd_status)
    backup = sub.add_parser("backup", help="Snapshot scopes+seed ledger (+credentials on flag).")
    backup.add_argument("--include-credentials", action="store_true")
    backup.set_defaults(func=cmd_backup)
    sync = sub.add_parser("sync", help="Fingerprint-gated graph re-analysis (closes acquired-judgement rebuild thread).")
    sync.add_argument("--dry-run", action="store_true")
    sync.set_defaults(func=cmd_sync)
    return parser


def main() -> int:
    args = build_parser().parse_args()
    try:
        return int(args.func(args))
    except SystemExit:
        raise
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())

def _base_unresolved(
    repository: str,
    revision: str | None,
    subject: str,
    code: str,
    evidence_ids: tuple[Any, ...],
    language_version: str | None,
) -> CodeFactResolutionV2:
    return CodeFactResolutionV2(
        status=CodeFactStatus.UNRESOLVED,
        repository=repository or "unknown",
        revision=revision or None,
        fact_category=JavaFactCategory.CONFIGURATION_FACT,
        semantic_stage=SemanticStage.DECLARATION,
        declaring_type="unknown",
        subject_identity=subject or "unknown",
        value_semantics=CodeValueSemantics.EXPLICIT_INITIALIZER,
        language_version=language_version,
        analysis_method="tree-sitter-range-v1",
        source_evidence_ids=tuple(e for e in evidence_ids if e is not None),
        declaration_location=SourceLocation(system="Git", identifier="unknown"),
        limitation_codes=(code,) if "," not in code else tuple(code.split(",")),
        parser_version=_p.parser_version(),
    )


def _ref(file_path: str, first_line: int, node: Any) -> str:
    start = first_line + node.start_point[0]
    end = first_line + node.end_point[0]
    return f"{file_path}:{start}-{end}"


def _annotations(declaration: Any, source: bytes) -> list[tuple[str, str, Any]]:
    """Return (annotation name, argument text, node) for declaration modifiers."""
    found: list[tuple[str, str, Any]] = []
    for child in declaration.children:
        if child.type != "modifiers":
            continue
        for modifier in child.children:
            if modifier.type not in {"marker_annotation", "annotation"}:
                continue
            name = ""
            args = ""
            for grand in modifier.children:
                if grand.type == "identifier" and not name:
                    name = _p.node_text(grand, source).strip()
                elif grand.type == "annotation_argument_list":
                    args = " ".join(_p.node_text(grand, source).split())
            if name:
                found.append((name, args, modifier))
    return found


def _string_arg(args: str) -> str:
    """First double-quoted literal inside annotation arguments, else raw args."""
    start = args.find('"')
    end = args.rfind('"')
    if 0 <= start < end:
        return args[start + 1 : end]
    return args.strip("() ")


def _declared_bindings(
    declaration: Any,
    source: bytes,
    symbol_name: str,
    first_line: int,
    source_path: str,
) -> tuple[list[dict[str, str]], list[str]]:
    """Extract declared bindings and qualifier notes from annotations."""
    bindings: list[dict[str, str]] = []
    qualifiers: list[str] = []
    annotations = _annotations(declaration, source)
    qualifier_names = [n for n, _, _ in annotations if n in _QUALIFIER_ANNOTATIONS]
    for name, args, node in annotations:
        ref = _ref(source_path, first_line, node)
        if name == "Bean":
            bindings.append(
                {
                    "kind": "bean_definition",
                    "detail": f"@Bean method {symbol_name} declares bean "
                    f"{_string_arg(args) or symbol_name}",
                    "range": ref,
                }
            )
        elif name in _COMPONENT_ANNOTATIONS:
            bindings.append(
                {
                    "kind": "component_declaration",
                    "detail": f"@{name} declares component {_string_arg(args) or symbol_name}",
                    "range": ref,
                }
            )
        elif name in _INJECT_ANNOTATIONS:
            bindings.append(
                {
                    "kind": "injection_point",
                    "detail": f"@{name} declares injection into {symbol_name}",
                    "range": ref,
                }
            )
        elif name == "Value" and "${" in args:
            bindings.append(
                {
                    "kind": "config_key",
                    "detail": f"@Value declares config key {_string_arg(args)} for {symbol_name}",
                    "range": ref,
                }
            )
        elif name == "ConfigurationProperties":
            bindings.append(
                {
                    "kind": "configuration_properties",
                    "detail": f"@ConfigurationProperties declares prefix "
                    f"{_string_arg(args)} for {symbol_name}",
                    "range": ref,
                }
            )
        elif name in _ROUTE_ANNOTATIONS:
            bindings.append(
                {
                    "kind": "route_declaration",
                    "detail": f"@{name} declares route {_string_arg(args)} for {symbol_name}",
                    "range": ref,
                }
            )
        elif name in _MAPPING_ANNOTATIONS:
            bindings.append(
                {
                    "kind": "persistence_mapping",
                    "detail": f"@{name} declares persistence mapping "
                    f"{_string_arg(args) or symbol_name}",
                    "range": ref,
                }
            )
        elif name in _LISTENER_ANNOTATIONS:
            bindings.append(
                {
                    "kind": "listener_binding",
                    "detail": f"@{name} declares listener binding "
                    f"{_string_arg(args) or symbol_name}",
                    "range": ref,
                }
            )
        elif name in _QUALIFIER_ANNOTATIONS:
            qualifiers.append(f"@{name}({_string_arg(args)})" if args else f"@{name}")
    if qualifiers and bindings:
        for binding in bindings:
            binding["detail"] += f" [qualifiers: {', '.join(qualifier_names)}]"
    return bindings, qualifier_names


def _boundary_codes(subtree_text: str, annotations: list[tuple[str, str, Any]]) -> list[str]:
    codes: list[str] = []
    names = {name for name, _, _ in annotations}
    if names & _LOMBOK_ANNOTATIONS or "lombok." in subtree_text:
        codes.append("lombok_generated_code")
    if any(name == "Value" and "${" not in args for name, args, _ in annotations):
        if "lombok_generated_code" not in codes:
            codes.append("lombok_generated_code")
    for code, markers in _BOUNDARY_MARKERS:
        if any(marker in subtree_text for marker in markers):
            codes.append(code)
    return codes


def _with_field_context(declaration: Any, source: bytes, subtree_text: str) -> str:
    """Boundary scan text: the declaration plus sibling field declarations.

    Injected client types (``RestTemplate rest``, ``Executor pool``) live on
    fields, not in the method body. Including sibling fields keeps the scan
    class-scoped without widening to the whole window.
    """
    enclosing: Any = declaration.parent
    while enclosing is not None and enclosing.type not in _TYPE_TYPES:
        enclosing = enclosing.parent
    if enclosing is None:
        return subtree_text
    body = next((c for c in enclosing.children if c.type == "class_body"), None)
    if body is None:
        return subtree_text
    fields = [
        _p.node_text(child, source)
        for child in body.children
        if child.type == "field_declaration" and child is not declaration
    ]
    return subtree_text + "\n" + "\n".join(fields)


def _find_symbol(root: Any, source: bytes, symbol_name: str) -> tuple[Any | None, str | None]:
    matches = []
    for node in _p.walk(root):
        if node.type not in _SYMBOL_TYPES:
            continue
        if node.type == "field_declaration":
            for child in node.children:
                if child.type != "variable_declarator":
                    continue
                name_node = child.child_by_field_name("name")
                if name_node is not None and _p.node_text(name_node, source) == symbol_name:
                    matches.append(node)
        else:
            name_node = node.child_by_field_name("name")
            if name_node is not None and _p.node_text(name_node, source) == symbol_name:
                matches.append(node)
    if not matches:
        return None, "symbol_not_in_window"
    if len(matches) > 1:
        return None, "ambiguous_symbol"
    return matches[0], None


def resolve_java_framework_boundary(
    evidence: Any,
    symbol_name: str,
    *,
    binding_hint: str | None = None,
    language_version: object = None,
) -> CodeFactResolutionV2:
    """Report declared DI/config bindings or named runtime boundaries."""
    lines, reason = java_source_lines(evidence)
    provenance = getattr(evidence, "provenance", None)
    location = getattr(provenance, "source_location", None)
    source_path = str(getattr(location, "file_path", "") or "")
    revision = str(getattr(location, "revision", "") or "")
    identifier = str(getattr(location, "identifier", "") or "")
    repository = repository_of(identifier, source_path)
    evidence_id = getattr(evidence, "evidence_id", None)
    evidence_ids = (evidence_id,) if evidence_id is not None else ()
    level = _lit.normalize_source_level(language_version)
    level_text = str(level) if level is not None else None
    subject = symbol_name or "unknown"

    if reason:
        return _base_unresolved(repository, revision, subject, reason, evidence_ids, level_text)
    assert location is not None
    if not symbol_name or not symbol_name.strip():
        return _base_unresolved(
            repository, revision, subject, "missing_symbol_name", evidence_ids, level_text
        )
    if not source_path.lower().endswith(".java"):
        return _base_unresolved(
            repository, revision, subject, "not_a_java_source_file", evidence_ids, level_text
        )
    if not repository:
        return _base_unresolved(
            repository,
            revision,
            subject,
            "repository_identity_unavailable",
            evidence_ids,
            level_text,
        )

    window_text = "\n".join(line.text for line in lines)
    source_bytes = window_text.encode("utf-8")
    try:
        tree = _p.parse_java(source_bytes)
    except Exception as exc:
        return _base_unresolved(
            repository,
            revision,
            subject,
            f"java_parser_unavailable:{type(exc).__name__}",
            evidence_ids,
            level_text,
        )
    if tree.root_node.has_error:
        return _base_unresolved(
            repository,
            revision,
            subject,
            "java_syntax_error_or_incomplete_source_window",
            evidence_ids,
            level_text,
        )

    declaration, failure = _find_symbol(tree.root_node, source_bytes, symbol_name)
    if declaration is None:
        assert failure is not None
        return _base_unresolved(repository, revision, subject, failure, evidence_ids, level_text)

    first_line = lines[0].number
    subtree_text = _p.node_text(declaration, source_bytes)
    annotations = _annotations(declaration, source_bytes)
    analyzed_text = _with_field_context(declaration, source_bytes, subtree_text)
    bindings, _ = _declared_bindings(
        declaration, source_bytes, symbol_name, first_line, source_path
    )
    codes = _boundary_codes(analyzed_text, annotations)

    if binding_hint is not None:
        hint = binding_hint.strip().lower()
        if not hint:
            return _base_unresolved(
                repository, revision, subject, "binding_hint_not_found", evidence_ids, level_text
            )
        bindings = [b for b in bindings if hint in b["kind"].lower() or hint in b["detail"].lower()]
        if not bindings and not codes:
            return _base_unresolved(
                repository, revision, subject, "binding_hint_not_found", evidence_ids, level_text
            )

    declaration_location = location.model_copy(
        update={
            "line_start": first_line + declaration.start_point[0],
            "line_end": first_line + declaration.end_point[0],
        }
    )

    if codes:
        assumptions = (
            "declared bindings only; applied behavior requires runtime evidence",
            (
                "missing runtime evidence named by limitation code; "
                "verdict ceiling LIKELY via CATEGORY_PROOF_RULES"
            ),
            "language_version is caller-attested, not build authority",
        )
        structured_fact: dict[str, Any] | None = {
            "kind": "declared_bindings_with_runtime_boundary",
            "symbol": symbol_name,
            "bindings": bindings,
            "boundary_codes": list(dict.fromkeys(codes)),
            "required_evidence": "runtime observation or container/config source "
            "outside this window",
            "notes": list(assumptions),
        }
        authored = " ".join([b["kind"] for b in bindings] + list(codes) + list(assumptions)).lower()
        assert not any(word in authored for word in _AUTHORED_WORDS_BANNED)
        return CodeFactResolutionV2(
            status=CodeFactStatus.PARTIAL,
            repository=repository,
            revision=revision,
            fact_category=JavaFactCategory.CONFIGURATION_FACT,
            semantic_stage=SemanticStage.DECLARATION,
            declaring_type="unknown",
            subject_identity=f"{source_path}#{symbol_name}",
            value_semantics=CodeValueSemantics.EXPLICIT_INITIALIZER,
            language_version=level_text,
            analysis_method="tree-sitter-range-v1",
            structured_fact=structured_fact,
            control_flow_refs=(_ref(source_path, first_line, declaration),),
            source_evidence_ids=evidence_ids,
            declaration_location=declaration_location,
            limitation_codes=tuple(
                dict.fromkeys(
                    [
                        *codes,
                        "requires_runtime_observation",
                        "applied_behavior_requires_runtime_evidence",
                    ]
                )
            ),
            assumptions=assumptions,
            parser_version=_p.parser_version(),
        )

    if not bindings:
        return _base_unresolved(
            repository,
            revision,
            subject,
            "no_binding_declaration_in_window",
            evidence_ids,
            level_text,
        )

    assumptions = (
        "declared bindings only; applied behavior requires runtime evidence",
        (
            "a configuration declaration never verifies as applied configuration; "
            "verdict ceiling LIKELY via CATEGORY_PROOF_RULES"
        ),
        "language_version is caller-attested, not build authority",
    )
    structured_fact = {
        "kind": "declared_bindings",
        "symbol": symbol_name,
        "bindings": bindings,
        "notes": list(assumptions),
    }
    authored = " ".join([b["kind"] for b in bindings] + list(assumptions)).lower()
    assert not any(word in authored for word in _AUTHORED_WORDS_BANNED)
    return CodeFactResolutionV2(
        status=CodeFactStatus.RESOLVED,
        repository=repository,
        revision=revision,
        fact_category=JavaFactCategory.CONFIGURATION_FACT,
        semantic_stage=SemanticStage.DECLARATION,
        declaring_type="unknown",
        subject_identity=f"{source_path}#{symbol_name}",
        value_semantics=CodeValueSemantics.EXPLICIT_INITIALIZER,
        language_version=level_text,
        analysis_method="tree-sitter-range-v1",
        structured_fact=structured_fact,
        control_flow_refs=(_ref(source_path, first_line, declaration),),
        source_evidence_ids=evidence_ids,
        declaration_location=declaration_location,
        assumptions=assumptions,
        parser_version=_p.parser_version(),
    )

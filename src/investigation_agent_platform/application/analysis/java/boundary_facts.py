# src/investigation_agent_platform/application/analysis/java/boundary_facts.py
"""Deterministic Java framework/external-boundary resolution (Phase 7, D6/D8).

``resolve_java_framework_boundary`` reports *declared* dependency-injection
and configuration bindings inside one revision-pinned source window as
``CONFIGURATION_FACT`` (verdict ceiling ``LIKELY`` via the existing
``CATEGORY_PROOF_RULES`` table; the verifier is never modified here).

Mandatory fail-closed rules:

- A declared binding (``@Bean``, ``@Value``, ``@ConfigurationProperties``,
  component/inject annotations, route and mapping annotations) carries its
  source location only. Applied behavior, container startup, transaction
  outcomes, and concurrent ordering are never verified from a declaration.
- Any framework/runtime mechanism in the analyzed declaration (reflection,
  proxies, annotation processing, Lombok, generated sources, JDBC,
  transactions, HTTP clients, brokers, caches, serialization, time, locale,
  randomness, async execution) yields PARTIAL with a named limitation code
  plus the missing runtime evidence note.
"""

